import assert from 'node:assert/strict';
const subject = await import('../src/lib/listingDraft.js').catch(() => ({}));
assert.equal(typeof subject.createListingDraftStore, 'function', 'Listing drafts must survive a reload');
const memory = new Map(), images = new Map();
let clock = 1000000000;
const storage = { getItem: (key) => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: (key) => memory.delete(key) };
const photoStorage = { get: async (key) => images.get(key), set: async (key, value) => images.set(key, value), remove: async (key) => images.delete(key) };
const store = subject.createListingDraftStore({ storage, photoStorage, now: () => clock });
const draft = { form: { type: 'lend', quantity: '2', description: 'A chair', contact: 'secret' }, selected: { id: 1, category_path: 'furniture/chair' }, position: [42.4, 19.2], address: 'Pickup square', addressVerified: true, token: 'secret', contacts: { telegram: 'secret' }, step: 3, existingPhotoUrls: ['https://example.test/old-photo.jpg'] };
draft.form.item_name = 'Portable camping chair with a folding frame';
const photos = [{ file: new File(['photo'], 'a.jpg', { type: 'image/jpeg' }), operationId: 'retry-1' }];
assert.deepEqual(await store.save('alice', null, draft, photos), { text: true, photos: true });
assert.equal((await store.load('alice', null)).data.form.description, 'A chair');
assert.equal((await store.load('alice', null)).data.form.item_name, draft.form.item_name);
const publicationId = '11111111-1111-4111-8111-111111111111';
await store.save('alice', null, { ...draft, publicationId }, photos);
assert.equal((await store.load('alice', null)).data.publicationId, publicationId, 'Publication identity must survive restoring a draft');
assert.equal((await store.load('alice', null)).photos[0].operationId, 'retry-1');
assert.equal(await store.load('bob', null), null);
assert.equal(await store.load('alice', 'edit-1'), null);
assert.ok(![...memory.values()][0].includes('secret'), 'Tokens and private contacts must never enter drafts');
await store.save('alice', 'edit-1', { ...draft, form: { ...draft.form, description: 'Editing' } }, []);
await store.discard('alice', null);
assert.equal(await store.load('alice', null), null);
assert.equal((await store.load('alice', 'edit-1')).data.form.description, 'Editing');
clock += 7 * 24 * 60 * 60 * 1000 + 1;
assert.equal(await store.load('alice', 'edit-1'), null);
assert.equal(images.size, 0);
const blocked = subject.createListingDraftStore({ storage: { getItem() { throw new Error('Blocked'); }, setItem() { throw new Error('Quota'); }, removeItem() {} }, photoStorage, now: () => clock });
assert.equal(await blocked.load('alice'), null);
assert.deepEqual(await blocked.save('alice', null, draft, photos), { text: false, photos: false });
const noImages = subject.createListingDraftStore({ storage, photoStorage: { ...photoStorage, set: async () => { throw new Error('Quota'); } }, now: () => clock });
await store.save('alice', null, draft, photos);
assert.deepEqual(await noImages.save('alice', null, draft, photos), { text: true, photos: false });
assert.equal((await noImages.load('alice', null)).data.form.quantity, '2');
assert.equal((await noImages.load('alice', null)).photos.length, 0, 'A failed photo save must not restore stale photos from an earlier revision');
assert.deepEqual((await noImages.load('alice', null)).data.existingPhotoUrls, ['https://example.test/old-photo.jpg'], 'Existing edit photos must survive unavailable IndexedDB');
console.log('Drafts passed: user/edit separation, privacy allowlist, explicit discard, expiry, storage fallbacks.');
