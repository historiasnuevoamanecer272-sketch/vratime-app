import assert from 'node:assert/strict';
const worker = new EventTarget(); worker.controller = {};
const registration = new EventTarget(); registration.waiting = null;
worker.getRegistration = async () => registration;
let reloads=0;
const environment={navigator:{serviceWorker:worker},location:{reload(){reloads++;}}};
Object.defineProperty(globalThis,'navigator',{value:environment.navigator,configurable:true});
globalThis.window=environment;
const update=await import('../src/lib/pwaUpdate.js');
const cleanup=update.enableAutomaticPwaRefresh();
worker.dispatchEvent(new Event('controllerchange'));
assert.equal(reloads,0,'A new service worker must not reload a filled form');
assert.equal(typeof update.subscribePwaUpdate,'function');
assert.equal(typeof update.applyPwaUpdate,'function');
let pending=false;
const unsubscribe=update.subscribePwaUpdate(value=>{pending=value;});
assert.equal(pending,true);
update.applyPwaUpdate(); assert.equal(reloads,1);
cleanup();unsubscribe();
console.log('PWA update passed: unsolicited activation preserves the form; reload requires explicit action.');
