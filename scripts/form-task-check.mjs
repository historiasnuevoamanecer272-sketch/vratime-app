import assert from 'node:assert/strict';
const subject = await import('../src/lib/formTaskScope.js').catch(() => ({}));
assert.equal(typeof subject.createFormTaskScope, 'function', 'Form work must be bound to its mounted user scope');
const scope = subject.createFormTaskScope('alice');
const task = scope.capture();
let finish, allocated = 0, mutations = 0;
const pending = subject.prepareScopedPreview(new Blob(['image']), { task, prepare: () => new Promise((resolve) => { finish = resolve; }), createObjectURL: () => { allocated += 1; return 'blob:late'; } });
scope.dispose();
finish(new Blob(['prepared']));
assert.equal(await pending, null);
assert.equal(allocated, 0, 'A late image result must not allocate an object URL after unmount');
const previewScope = subject.createFormTaskScope('alice');
let released = 0;
const ready = await subject.prepareScopedPreview(new Blob(['image']), { task: previewScope.capture(), prepare: async (blob) => blob, createObjectURL: () => 'blob:ready', revokeObjectURL: () => { released += 1; } });
assert.equal(ready.preview, 'blob:ready');
previewScope.dispose();
assert.equal(released, 1, 'An allocated preview must be owned before the component resumes after await');
assert.equal(task.signal.aborted, true);
scope.activate();
assert.equal(task.isCurrent(), false, 'StrictMode remount must not revive an old task');
let currentUser = 'alice';
const current = scope.capture();
await current.authorize(async () => ({ data: { user: { id: currentUser } } }));
currentUser = 'bob';
await assert.rejects(current.mutate(async () => { mutations += 1; }, async () => ({ data: { user: { id: currentUser } } })), { code: 'form_auth_changed' });
assert.equal(mutations, 0, 'An A-to-B auth switch must stop the next authenticated mutation');
const another = subject.createFormTaskScope('alice');
let finishMutation;
const first = another.capture();
const flow = first.mutate(() => new Promise((resolve) => { finishMutation = resolve; }));
await Promise.resolve();
another.dispose(); finishMutation('saved');
await assert.rejects(flow, { code: 'form_auth_changed' });
assert.equal(await subject.prepareScopedPreview(new Blob(['image']), { task: scope.capture(), isCurrent: () => false, prepare: async (blob) => blob, createObjectURL: () => { allocated += 1; } }), null);
console.log('Form tasks passed: late previews, abort, StrictMode generations and auth-scoped mutation boundaries.');
