import assert from 'node:assert/strict';
import { nextDealStep, formatLocalDeadline } from '../src/lib/dealNextStep.js';
import { errorMessageKey } from '../src/lib/userErrors.js';
import { subscribeConnection } from '../src/lib/connectionState.js';
const now = new Date('2026-10-19T10:00:00Z');
const pending = { status:'pending',is_listing_owner:true,role:'giver',expires_at:'2026-10-19T11:00:00Z' };
assert.equal(nextDealStep(pending,null,now),'acceptRequest');
assert.equal(nextDealStep({...pending,is_listing_owner:false},null,now),'waitOwner');
assert.equal(nextDealStep({...pending,expires_at:'2026-10-19T09:00:00Z'},null,now),'expired');
const accepted={...pending,status:'reserved',accepted_at:'2026-10-19T09:00:00Z'};
assert.equal(nextDealStep(accepted,null,now),'arrangeMeeting');
assert.equal(nextDealStep(accepted,{state:'scheduled',scheduled_for:'2026-10-19T10:30:00Z'},now),'attendMeeting');
assert.equal(nextDealStep(accepted,{state:'scheduled',scheduled_for:'2026-10-19T09:30:00Z'},now),'confirmTransfer');
assert.equal(nextDealStep({...accepted,giver_confirmed_at:'2026-10-19T09:30:00Z'},null,now),'waitPartner');
assert.equal(nextDealStep({...accepted,role:'taker',giver_confirmed_at:'2026-10-19T09:30:00Z'},null,now),'confirmTransfer');
assert.equal(nextDealStep({...accepted,canceled_at:'2026-10-19T09:45:00Z'},null,now),'closed');
assert.equal(nextDealStep({...accepted,completed_at:'2026-10-19T09:45:00Z'},null,now),'review');
assert.equal(nextDealStep({...accepted,completed_at:'2026-10-19T09:45:00Z',my_review_rating:5},null,now),'finished');
const loan={...accepted,listing_type:'lend',handed_over_at:'2026-10-19T09:10:00Z',expires_at:'2026-10-19T09:00:00Z'};
assert.equal(nextDealStep(loan,null,now),'arrangeReturn','issued loan must not follow an expired reservation timer');
assert.equal(nextDealStep({...loan,return_due_at:'2026-10-19T09:59:00Z'},null,now),'confirmReturn');
assert.equal(nextDealStep({...loan,lender_return_confirmed_at:'2026-10-19T09:50:00Z'},null,now),'waitPartner');
assert.equal(nextDealStep({...loan,returned_at:'2026-10-19T09:55:00Z'},null,now),'review');
assert.equal(nextDealStep(accepted,{state:'canceled',scheduled_for:'2026-10-19T09:30:00Z'},now),'arrangeMeeting');
assert.equal(formatLocalDeadline('invalid','ru'),'');
assert.ok(formatLocalDeadline(accepted.expires_at,'me').length>5);
assert.equal(errorMessageKey(new Error('new row violates row-level security policy')),'permission');
assert.equal(errorMessageKey({code:'23505',message:'duplicate key value violates unique constraint'}),'retryState');
assert.equal(errorMessageKey({message:'Failed to fetch'}),'network');
assert.equal(errorMessageKey({message:'JWT expired'}),'session');
assert.equal(errorMessageKey({message:'quantity_not_available'}),'quantity');
assert.equal(errorMessageKey({message:'unexpected postgres text with private details'}),'save');
assert.equal(nextDealStep(accepted,undefined,now),'checkMeeting');
const events=new Map(),seen=[];
const host={navigator:{onLine:true},addEventListener:(name,fn)=>events.set(name,fn),removeEventListener:(name)=>events.delete(name)};
const stop=subscribeConnection(host,state=>seen.push(state));
host.navigator.onLine=false;events.get('offline')();
host.navigator.onLine=true;events.get('online')();
assert.deepEqual(seen,[false,true]);
stop();assert.equal(events.size,0);
console.log('Reliability UX: next-action, deadline, safe-error and connection checks passed.');
